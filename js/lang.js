var language = localStorage.getItem("language") || (window.navigator.userLanguage || window.navigator.language);
language = language.substring(0,2);
if (!languages[language]) {
  language = "en";
}

function applyLanguage() {
  if (!languages[language]) return;

  document.getElementById("lblTitle").innerHTML = languages[language]["Title"];
  document.getElementById("lblSetAll").innerHTML = languages[language]["SetAll"];
  document.getElementById("lblSettings").innerHTML = languages[language]["Settings"];
  document.getElementById("lblv2Level").innerHTML = languages[language]["v2Level"];
  document.getElementById("lblAchievement25").innerHTML = languages[language]["Achievement25"];
  document.getElementById("lblMasteryBoost17").innerHTML = languages[language]["MasteryBoost17"];
  document.getElementById("lblTarget").innerHTML = languages[language]["Target"];
  document.getElementById("lblMagic").innerHTML = languages[language]["Magic"];
  document.getElementById("lblCredits1").innerHTML = languages[language]["Credits1"];
  document.getElementById("lblCredits2").innerHTML = languages[language]["Credits2"];
  document.getElementById("lblCredits3").innerHTML = languages[language]["Credits3"];
  document.getElementById("lblCredits4").innerHTML = languages[language]["Credits4"];
  document.getElementById("lblCredits5").innerHTML = languages[language]["Credits5"];
  document.getElementById("linkWiki").innerHTML = languages[language]["LinkWiki"];
  document.getElementById("linkGitHub").innerHTML = languages[language]["LinkGitHub"];
  document.getElementById("lblNotation").innerHTML = languages[language]["lblNotation"];
  document.getElementById("lbOriginal").innerHTML = languages[language]["lbOriginal"];
  document.getElementById("lbNormal").innerHTML = languages[language]["lbNormal"];
  document.getElementById("lbAbstract").innerHTML = languages[language]["lbAbstract"];
  document.getElementById("lbScientific").innerHTML = languages[language]["lbScientific"];


  // Обновляем значение в селекте, если есть
  const langSelect = document.getElementById("languageSelect");
  if (langSelect) langSelect.value = language;
}

function changeLanguage() {
  const selectedLang = document.getElementById("languageSelect").value;
  localStorage.setItem("language", selectedLang);
  language = selectedLang;
  applyLanguage();
  calculate();
}
